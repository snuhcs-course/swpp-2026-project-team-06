const LABELS: [keyof BusinessInfo, string][] = [
  ["name", "상호"],
  ["owner", "대표자"],
  ["registrationNo", "사업자등록번호"],
  ["mailOrderNo", "통신판매업 신고번호"],
  ["address", "주소"],
  ["phone", "연락처"],
  ["email", "이메일"],
  ["privacyOfficer", "개인정보 보호책임자"],
];

/** 값이 있는 항목만 [이름, 값]으로. 하나도 없으면 빈 배열(화면은 ‘테스트 서비스’만 보인다, policy.md 6장) */
export function businessLines(info: BusinessInfo = business): [string, string][] {
  return LABELS.flatMap(([key, label]) => {
    const value = info[key];
    return value ? [[label, value] as [string, string]] : [];
  });
}

/** 호스팅서비스 제공자(전자상거래법 제10조 제1항 제6호, 시행령 제11조의4). 사업자 정보가 아니라 레포에 둔다 */
export const HOSTING_PROVIDER = "Vercel Inc.";

/** 사이트 하단 표시 줄: 사업자 정보(값 있는 것만) + 호스팅서비스 제공자 */
export function siteLines(info: BusinessInfo = business): [string, string][] {
  return [...businessLines(info), ["호스팅서비스 제공자", HOSTING_PROVIDER]];
}

