const clean = (v: string | undefined) => (v ?? "").trim() || undefined;

/** 빌드 때 넣은 사업자 정보. Expo는 process.env.EXPO_PUBLIC_* 를 값으로 바꾸므로 한 줄씩 그대로 적는다 */
